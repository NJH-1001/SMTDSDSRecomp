"""Package only a manifest-audited source kit and an original setup executable."""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile


def audit(root):
    data=json.loads((root / "SOURCE_MANIFEST.json").read_text())
    expected=set(data["files"])|{"SOURCE_MANIFEST.json"}
    actual={p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() and ".git" not in p.relative_to(root).parts}
    if actual!=expected:
        raise RuntimeError(f"Unmanifested/missing files: {sorted(actual ^ expected)[:20]}")
    for name,digest in data["files"].items():
        path=root / name
        parts=Path(name).parts
        if Path(name).is_absolute() or ".." in parts or any(p in {"generated","local","saves","captures","ghidra",".git"} for p in parts):
            raise RuntimeError(f"Private/unsafe path refused: {name}")
        if path.suffix.lower() in {".nds",".rom",".bin",".exe",".dll",".sav",".dsv",".bmp",".png",".pcap",".zip",".gz",".o",".obj",".a",".lib",".pdb"}:
            raise RuntimeError(f"Private/binary artifact refused: {name}")
        content=path.read_bytes()
        if b"\0" in content or content.startswith(b"/* AUTO-GENERATED by nds_recompile."):
            raise RuntimeError(f"Non-source or generated bank refused: {name}")
        if path.is_symlink() or hashlib.sha256(content).hexdigest()!=digest:
            raise RuntimeError(f"Source integrity failure: {name}")
    return len(actual)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source",type=Path,required=True)
    parser.add_argument("--setup",type=Path)
    parser.add_argument("--platform",choices=("Windows-x86_64","Linux-x86_64","macOS-x86_64","macOS-arm64"))
    parser.add_argument("--output",type=Path)
    args=parser.parse_args();count=audit(args.source)
    print(f"Source audit passed: {count} files")
    if not args.output:return
    if not args.setup or not args.platform:
        parser.error("Packaging requires --setup and --platform")
    args.output.parent.mkdir(parents=True,exist_ok=True)
    setup_name="SMTDSDSRecomp-Setup"+(".exe" if args.platform.startswith("Windows") else "")
    setup=args.setup.read_bytes()
    if len(setup)>8*1024*1024 or b"SMTDSDSRecomp ROM-free setup 0.1.0" not in setup:
        raise RuntimeError("Setup asset does not match the original small ROM-free host")
    with zipfile.ZipFile(args.output,"w",zipfile.ZIP_DEFLATED) as archive:
        manifest=json.loads((args.source / "SOURCE_MANIFEST.json").read_text())
        for name in sorted([*manifest["files"],"SOURCE_MANIFEST.json"]):
            archive.write(args.source / name,name)
        info=zipfile.ZipInfo(setup_name);info.external_attr=(0o100755<<16)
        archive.writestr(info,setup)
    digest=hashlib.sha256(args.output.read_bytes()).hexdigest()
    args.output.with_suffix(args.output.suffix+".sha256").write_text(f"{digest}  {args.output.name}\n")
    print(f"Packaged {args.platform}: {args.output.name} SHA256 {digest}")


if __name__=="__main__":main()
