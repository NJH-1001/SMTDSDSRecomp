"""Export only audited source/configuration, never a development directory tree."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
import subprocess

ROOT=Path(__file__).resolve().parents[1]
EXT={".def",".mm",".s",".asm",".c",".cpp",".cc",".h",".hpp",".in",".inc",".cmake",".py",".toml",".json",".md",".txt",".sh",".ps1",".yml",".yaml",".glsl",".vert",".frag"}
PRIVATE_PARTS={".git","generated","local","build","saves","captures","ghidra","dist","__pycache__"}


def allowed(path):
    return not any(p in PRIVATE_PARTS or p.startswith("build-") or p.startswith("build_") for p in path.parts) and (path.suffix.lower() in EXT or path.name in {"LICENSE","LICENSE-GPL","LICENSE-MIT","COPYING","COPYRIGHT","CMakeLists.txt","VERSION",".gitignore",".gitattributes"})


def git_files(root):
    result=subprocess.check_output(["git","-C",str(root),"ls-files","-c","-o","--exclude-standard","-z"])
    return sorted(set(Path(p.decode()) for p in result.split(b"\0") if p))


def export(destination):
    if destination.exists():
        raise RuntimeError("Export destination must not already exist")
    destination.mkdir(parents=True)
    records={}
    def copy(root,relative,target):
        path=root / relative
        if path.is_symlink() or not path.is_file() or not allowed(relative):
            return
        data=path.read_bytes()
        # Fail closed for executable/archive magic, generated bank source, and
        # binary content regardless of a misleading filename extension.
        if b"\0" in data or data.startswith((b"MZ",b"PK\x03\x04",b"\x7fELF",b"\x1f\x8b")):
            raise RuntimeError(f"Non-source data refused: {relative}")
        if data.startswith(b"/* AUTO-GENERATED by nds_recompile."):
            raise RuntimeError(f"Generated bank refused: {relative}")
        out=destination / target
        out.parent.mkdir(parents=True,exist_ok=True);out.write_bytes(data)
        records[target.as_posix()]=hashlib.sha256(data).hexdigest()
    # Explicit project allowlist; local status/capture docs are not release data.
    for name in ("README.md","PUBLIC_DISTRIBUTION.md","NOTICE.md","LICENSE",".gitignore",".gitattributes"):
        copy(ROOT,Path(name),Path(name))
    for folder in ("config","tools","setup","docs",".github"):
        for path in sorted((ROOT / folder).rglob("*")):
            if path.is_file():
                rel=path.relative_to(ROOT)
                # Developer probe scripts are not part of the installation API.
                if folder=="tools" and path.name not in {"install.py","play.py","verify_inputs.py","ci_compile.py","export_release_source.py","package_release.py","prepare_dependencies.py","bootstrap_sdl.py","audit_package.py"}:
                    continue
                copy(ROOT,rel,rel)
    framework=ROOT.parent / "ndsrecomp"
    helpers={"coverage_stream.py","ingest_coverage_manifests.py","rom_alias.py","gen_freebios_embed.py"}
    for rel in git_files(framework):
        keep=rel.parts[0] in {"runner","recompiler","cmake"}
        keep|=rel.parts[0]=="bios" and rel.suffix==".toml"
        keep|=rel.parts[0]=="tools" and rel.name in helpers
        keep|=rel.as_posix()=="oracle/_client.py"
        keep|=rel.as_posix()=="launcher/nds_input_bindings.h"
        keep|=rel.name in {"LICENSE","LICENSE-GPL","LICENSE-MIT","VERSION"} and len(rel.parts)==1
        # The open-source fallback BIOS is generated on the user's machine too.
        if keep:
            copy(framework,rel,Path("deps/ndsrecomp") / rel)
    core=framework / "external/arm-recomp-core"
    for rel in git_files(core):
        if rel.parts[0] in {"common","profiles","cmake"} or rel.name.startswith(("LICENSE","NOTICE")):
            copy(core,rel,Path("deps/ndsrecomp/external/arm-recomp-core") / rel)
    free=framework / "third_party/freebios"
    copy(free,Path("LICENSE.txt"),Path("deps/ndsrecomp/third_party/freebios/LICENSE.txt"))
    ui=ROOT.parent / "recomp-ui"
    for name in ("LICENSE","src/recomp_runtime_ui.h","src/common/recomp_runtime_ui.c","src/common/recomp_runtime_ui_internal.h","src/common/launcher_theme.h"):
        rel=Path(name);copy(ui,rel,Path("deps/recomp-ui") / rel)
    # Original top-level game settings, without a developer-specific file path.
    copy(ROOT,Path("game.toml"),Path("game.toml"))
    (destination / "SOURCE_MANIFEST.json").write_text(json.dumps({"format":1,"files":records},indent=2)+"\n")
    print(f"Exported {len(records)} source/configuration files; no generated banks or input images")


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("destination",type=Path)
    export(parser.parse_args().destination.resolve())
